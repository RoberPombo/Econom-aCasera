export type ReleaseNoteBlock =
  | { kind: "title"; text: string }
  | { kind: "section"; text: string }
  | { kind: "item"; text: string }
  | { kind: "text"; text: string };

const SECTION_TITLES: Record<string, string> = {
  "BREAKING CHANGES": "Cambios incompatibles",
  "Bug Fixes": "Correcciones",
  "Build System": "Sistema de compilación",
  Chores: "Tareas de mantenimiento",
  "Code Refactoring": "Refactorización",
  "Continuous Integration": "Integración continua",
  Documentation: "Documentación",
  Features: "Novedades",
  "Performance Improvements": "Mejoras de rendimiento",
  Reverts: "Revertidos",
  Styles: "Estilos",
  Tests: "Pruebas",
};

function stripInlineMarkdown(text: string): string {
  return text
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/__([^_]+)__/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/_([^_]+)_/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

function translateSection(text: string): string {
  const normalized = text.replace(/^⚠\s*/, "");
  return SECTION_TITLES[normalized] ?? normalized;
}

/**
 * Turns the Markdown release notes generated by release-please into plain
 * blocks the update dialog can render without pulling in a Markdown parser.
 */
export function formatReleaseNotes(notes: string): ReleaseNoteBlock[] {
  const blocks: ReleaseNoteBlock[] = [];

  for (const rawLine of notes.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) continue;

    const heading = line.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      const text = stripInlineMarkdown(heading[2]);
      if (!text) continue;
      blocks.push(
        heading[1].length <= 2
          ? { kind: "title", text }
          : { kind: "section", text: translateSection(text) },
      );
      continue;
    }

    const item = line.match(/^[*-]\s+(.*)$/);
    if (item) {
      const text = stripInlineMarkdown(item[1]).replace(
        /\s+\([0-9a-f]{7,40}\)$/i,
        "",
      );
      if (text) blocks.push({ kind: "item", text });
      continue;
    }

    const text = stripInlineMarkdown(line);
    if (text) blocks.push({ kind: "text", text });
  }

  return blocks;
}
